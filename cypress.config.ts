import { appendFileSync } from 'node:fs';
import { rm } from 'node:fs/promises';
import { defineConfig } from 'cypress';
import onFix from 'cypress-on-fix';
import createBundler from '@bahmutov/cypress-esbuild-preprocessor';
import { addCucumberPreprocessorPlugin } from '@badeball/cypress-cucumber-preprocessor';
import { createEsbuildPlugin } from '@badeball/cypress-cucumber-preprocessor/esbuild';
import { ReportingSubject } from './src/core/reporting/ReportingSubject';
import { ConsoleObserver } from './src/core/reporting/ConsoleObserver';
import { GithubActionsSummaryObserver } from './src/core/reporting/GithubActionsSummaryObserver';
import { readRunLabels } from './src/core/reporting/runLabels';
import { toTestResults } from './src/core/reporting/afterSpecMapper';
import { isCompletedRun, toRunMetadata } from './src/core/reporting/runSummary';
import { createTestRailObserver } from './src/core/reporting/testrail/createTestRailObserver';

export default defineConfig({
  projectId: '5v45hh',
  viewportWidth: 1280,
  viewportHeight: 800,
  // Two retries in CI absorb Render's free-tier hiccups; none in open mode
  // so a developer sees the first failure, not the third. Every retry is
  // one more `attempts` on the TestResult row - the number is reported,
  // not hidden.
  retries: { runMode: 2, openMode: 0 },
  e2e: {
    baseUrl: 'https://omnipizza-frontend.onrender.com',
    specPattern: ['cypress/e2e/**/*.feature'],
    supportFile: 'cypress/support/e2e.ts',
    async setupNodeEvents(cypressOn, config) {
      // Cypress keeps ONE handler per node event: the last on('after:spec', ...) wins and every
      // earlier one is dropped, silently. addCucumberPreprocessorPlugin registers before:run,
      // after:run, before:spec, after:spec and after:screenshot; this file registers three of
      // those too. Without this proxy the preprocessor's handlers never ran - unnoticed so far
      // only because no cucumber report is enabled, so they return early. cypress-on-fix fans one
      // Cypress slot out to every listener, awaited in registration order.
      // Proof: src/core/reporting/cypressOnFix.node.test.ts. Live: DEBUG=cypress-on-fix cypress run.
      const on = onFix(cypressOn);
      await addCucumberPreprocessorPlugin(on, config);
      // The .md text loader is what lets cy.prompt's natural-language steps
      // live in a markdown file instead of TypeScript string literals: the
      // import becomes a plain string at bundle time, so the strategy that
      // consumes it stays synchronous (cy.fixture/cy.readFile would force a
      // Chainable through the whole CheckoutUiStrategy interface).
      on(
        'file:preprocessor',
        createBundler({ plugins: [createEsbuildPlugin(config)], loader: { '.md': 'text' } }),
      );

      // Replaces trashAssetsBeforeRuns, which cannot succeed on Windows.
      // Cypress's bundled `trash` shells out to windows-trash.exe, and that
      // binary exits 255 on any directory containing a file inside a
      // subdirectory - bisected 2026-08-21: a flat directory of files
      // trashes fine, an empty subdirectory trashes fine, one file one level
      // down fails. Cypress's own screenshot layout is always
      // screenshots/<spec path>/<test name>.png, so the feature is
      // permanently broken here and prints a warning on every single run.
      //
      // Note this is a permanent delete rather than a Recycle Bin move.
      // That is fine for these two folders specifically - both are
      // gitignored and regenerated by the next run - but it is a real
      // behaviour change from what it replaces.
      on('before:run', async () => {
        const folders = [config.screenshotsFolder, config.videosFolder];
        await Promise.all(
          folders.filter((folder): folder is string => typeof folder === 'string').map((folder) => rm(folder, { recursive: true, force: true })),
        );
      });

      const reportingSubject = new ReportingSubject();
      reportingSubject.subscribe(new ConsoleObserver());
      reportingSubject.subscribe(new GithubActionsSummaryObserver(process.env.GITHUB_STEP_SUMMARY));

      // Labels are read once per run: config.expose already holds every
      // `--expose K=V` pair merged over the `expose` block below.
      const labels = readRunLabels(config.expose);

      on('after:spec', (spec, results) => {
        // Opt-in raw evidence: AFTER_SPEC_DUMP=<path> appends one JSON line per
        // spec. It is what the mapper was designed from and what any later
        // agent can replay offline; unset, nothing is written.
        const dumpPath = process.env.AFTER_SPEC_DUMP;
        if (dumpPath) appendFileSync(dumpPath, `${JSON.stringify({ spec, results, expose: config.expose })}\n`);
        reportingSubject.notify(toTestResults(spec.relative, results, labels));
      });

      // TestRail is opt-in: subscribed only when TESTRAIL_URL is set (process.env, Node-side - no
      // Cypress.env/expose involved). TESTRAIL_DRY_RUN=1 prints the payloads instead of sending.
      const testRailObserver = createTestRailObserver(process.env, config.projectRoot);
      if (testRailObserver) reportingSubject.subscribeRun(testRailObserver);

      // Run-level seam: fires once per `cypress run`, after the last spec, and Cypress awaits the
      // promise. `results` is undefined under `cypress open` and has no `runs` when Cypress could
      // not start the run - both are "nothing to report".
      on('after:run', async (results) => {
        if (!isCompletedRun(results)) return;
        await reportingSubject.notifyRunComplete(toRunMetadata(results, config.expose));
      });

      return config;
    },
  },
  // `expose`, not `env`: Cypress 15 deprecated Cypress.env() because any
  // browser code on the page could read it. Nothing this framework passes
  // is a secret - the backend URL and the UI-strategy switch are both
  // public config - so both moved to expose, and no Cypress.env() call is
  // left in our own code. If a real secret ever has to reach a test,
  // cy.env() is the API for that.
  //
  // allowCypressEnv STAYS ON, and that is not an oversight. Setting it to
  // false is what the deprecation warning asks for, but it makes every
  // single spec fail: @badeball/cypress-cucumber-preprocessor calls
  // `createTestFilter(gherkinDocument, Cypress.env())` while building the
  // tests for each .feature - its tag-filtering path, unconditional, on
  // every file. Verified live 2026-08-21: with it off, 3 of 3 specs die
  // before a test runs. 26.0.0 is the latest published version, so there is
  // no release to upgrade into yet.
  //
  // So the run-level warning stays until the preprocessor migrates. Retry
  // this flag on the next @badeball release; the only other route is
  // patching the dependency, which trades a cosmetic warning for a
  // permanent maintenance burden.
  expose: {
    apiUrl: 'https://omnipizza-backend.onrender.com',
  },
  trashAssetsBeforeRuns: false,
  reporter: 'mochawesome',
  reporterOptions: {
    reportDir: 'cypress/reports/mochawesome',
    overwrite: false,
    html: true,
    json: true,
  },
});
