import { rm } from 'node:fs/promises';
import { defineConfig } from 'cypress';
import createBundler from '@bahmutov/cypress-esbuild-preprocessor';
import { addCucumberPreprocessorPlugin } from '@badeball/cypress-cucumber-preprocessor';
import { createEsbuildPlugin } from '@badeball/cypress-cucumber-preprocessor/esbuild';
import { ReportingSubject } from './src/core/reporting/ReportingSubject';
import { ConsoleObserver } from './src/core/reporting/ConsoleObserver';
import { GithubActionsSummaryObserver } from './src/core/reporting/GithubActionsSummaryObserver';
import type { TestResult } from './src/core/reporting/Observer';

export default defineConfig({
  projectId: '5v45hh',
  viewportWidth: 1280,
  viewportHeight: 800,
  // Chrome, not Electron. 16 deprecates Electron as a test browser (a
  // warning at the top of every run), keeps it on the legacy HTTP/1.1 proxy
  // path while Chrome gets the native network (HTTP/2), and ships with an
  // open Windows regression - cypress-io/cypress#34771, headless Electron
  // screenshots/videos come out 1264x712 instead of 1280x720. CI passes
  // --browser chrome explicitly as well; this covers local runs.
  defaultBrowser: 'chrome',
  // keystrokeDelay is left at 16's new default of 0 ms (was 10). Checked
  // rather than assumed, because fillField's have.value guard and the
  // phone field's "+" normalisation are exactly where a typing-speed change
  // would show: 2026-09-02, checkout.feature twice in Chrome, 5 markets
  // each, 10/10 at 0 ms.
  e2e: {
    baseUrl: 'https://omnipizza-frontend.onrender.com',
    specPattern: ['cypress/e2e/**/*.feature'],
    supportFile: 'cypress/support/e2e.ts',
    async setupNodeEvents(on, config) {
      await addCucumberPreprocessorPlugin(on, config);
      // The .md text loader is what lets cy.prompt's natural-language steps
      // live in a markdown file instead of TypeScript string literals: the
      // import becomes a plain string at bundle time, so the strategy that
      // consumes it stays synchronous (cy.fixture/cy.readFile would force a
      // Chainable through the whole CheckoutUiStrategy interface).
      on(
        'file:preprocessor',
        createBundler({ plugins: [createEsbuildPlugin(config)], loader: { '.md': 'text' } }),
      );

      // Replaces trashAssetsBeforeRuns, which cannot succeed on Windows.
      // Cypress's bundled `trash` shells out to windows-trash.exe, and that
      // binary exits 255 on any directory containing a file inside a
      // subdirectory - bisected 2026-08-21: a flat directory of files
      // trashes fine, an empty subdirectory trashes fine, one file one level
      // down fails. Cypress's own screenshot layout is always
      // screenshots/<spec path>/<test name>.png, so the feature is
      // permanently broken here and prints a warning on every single run.
      //
      // Note this is a permanent delete rather than a Recycle Bin move.
      // That is fine for these two folders specifically - both are
      // gitignored and regenerated by the next run - but it is a real
      // behaviour change from what it replaces.
      on('before:run', async () => {
        const folders = [config.screenshotsFolder, config.videosFolder];
        await Promise.all(
          folders.filter((folder): folder is string => typeof folder === 'string').map((folder) => rm(folder, { recursive: true, force: true })),
        );
      });

      const reportingSubject = new ReportingSubject();
      reportingSubject.subscribe(new ConsoleObserver());
      reportingSubject.subscribe(new GithubActionsSummaryObserver(process.env.GITHUB_STEP_SUMMARY));

      on('after:spec', (spec, results) => {
        const sliceMatch = spec.relative.match(/[\\/]e2e[\\/]([^\\/]+)[\\/]/);
        const slice = sliceMatch ? sliceMatch[1] : 'unknown';
        const testResults = (results?.tests ?? []).map((t) => ({
          specPath: spec.relative,
          title: t.title.join(' > '),
          state: t.state as TestResult['state'],
          durationMs: t.duration ?? 0,
          slice,
        }));
        reportingSubject.notify(testResults);
      });

      return config;
    },
  },
  // `expose`, not `env`. Cypress 15.10 deprecated Cypress.env() because any
  // browser code on the page could read it, and Cypress 16 removed it
  // outright - together with the `allowCypressEnv` migration flag and the
  // `env` key in per-test overrides. Nothing this framework passes is a
  // secret (the backend URL and the UI-strategy switch are both public
  // config), so both live here, are read with Cypress.expose() in the
  // browser, and are set from the CLI with `--expose KEY=VALUE`. `--env`
  // still exists in 16 but only feeds config.env in Node: nothing in the
  // browser reads it synchronously any more (the async cy.env() is its one
  // remaining reader), so it is useless for these two values. If a real
  // secret ever has to reach a test, cy.env() is the API for that.
  //
  // History, because an earlier version of this comment said the opposite:
  // on 15.21 with @badeball/cypress-cucumber-preprocessor 26.0.0 the
  // run-level allowCypressEnv warning could not be silenced - 26.x called
  // Cypress.env() itself while building each .feature's tests, so turning
  // the flag off killed every spec (verified live 2026-08-21). 27.0.0
  // (2026-08-27) stopped doing that on Cypress >= 15.17 and reads its own
  // overrides from --expose instead; 28.0.0 (2026-09-02) is the first
  // release whose peer range admits Cypress 16. Do not re-add
  // allowCypressEnv: 16 prints an ALLOW_CYPRESS_ENV_REMOVED warning on
  // every run for the removed key (a warning, not a validation error -
  // packages/config marks it isWarning: true).
  expose: {
    apiUrl: 'https://omnipizza-backend.onrender.com',
  },
  trashAssetsBeforeRuns: false,
  reporter: 'mochawesome',
  reporterOptions: {
    reportDir: 'cypress/reports/mochawesome',
    overwrite: false,
    html: true,
    json: true,
  },
});
